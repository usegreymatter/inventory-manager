#!/usr/bin/env python3
"""Generate the fully fictional five-product sample; never reads company data.

Only Python's seeded PRNG, fixed constants and fictional catalogue metadata are
used. --sync-fixtures also replaces embedded sample payloads in regression source
fixtures and golden inputs, retaining their independently frozen engine code.
Expected numerical results are regenerated separately by golden_diff.py.
"""
import argparse
import hashlib
import json
from pathlib import Path
import random
import re

ROOT = Path(__file__).resolve().parents[1]
SEED = 731209
MONTHS = ['2025-11', '2025-12'] + [f'2026-{m:02d}' for m in range(1, 11)]
PROVENANCE = f'fully synthetic, generated by scripts/generate_sample.py (seed {SEED})'
# Generic mnemonic SKU identifiers are retained for UI/regression compatibility;
# every quantity, demand pattern, receipt and supplier below is fictional.
CATALOGUE = [
    ('SEAL-CLR-300', 'Clear silicone sealant 300ml', 'units', 'Sealants', 'Fictional Hardware Supply', 'smooth', 340, 21),
    ('UL-FOAM-GRN', 'Foam floor underlay roll', 'm', 'Underlay', 'Fictional Flooring Supply', 'intermittent', 7, None),
    ('GRT-GRY-5', 'Tile adhesive 20kg', 'bag', 'Adhesives', 'Fictional Hardware Supply', 'seasonal', 90, 35),
    ('TRM-ALU-25', 'Aluminium edge trim 25mm', 'm', 'Trims', 'Fictional Flooring Supply', 'new', 42, 14),
    ('SEAL-WHT-300', 'White silicone sealant 300ml', 'units', 'Sealants', 'Fictional Hardware Supply', 'dying', 5, None),
]


def generate():
    rng = random.Random(SEED)
    items = []
    for sku, name, unit, category, supplier, pattern, stock, lead in CATALOGUE:
        if pattern == 'smooth':
            sales = [rng.randint(61, 83) for _ in MONTHS]
        elif pattern == 'intermittent':
            sales = [rng.randint(18, 37) if i in (1, 5, 8, 11) else 0 for i in range(12)]
        elif pattern == 'seasonal':
            sales = [max(1, n + rng.randint(-4, 4)) for n in (22, 25, 30, 38, 62, 89, 112, 106, 71, 45, 29, 20)]
        elif pattern == 'new':
            sales = [0] * 8 + [rng.randint(8, 14), rng.randint(17, 22), rng.randint(26, 32), rng.randint(37, 43)]
        else:
            sales = [max(0, 88 - i * 11 + rng.randint(-3, 3)) if i < 8 else 0 for i in range(12)]
        historical = {m: (sales[i] if i in (0, 4, 8) else 0) for i, m in enumerate(MONTHS)}
        item: dict = dict(sku=sku, name=name, unit=unit, on_hand=stock,
                    supplier_days=lead, open_receipts=[], monthly_sales=sales,
                    receipts={}, category=category, supplier=supplier,
                    historical_receipts=historical)
        if pattern == 'smooth':
            item.update(minimum_order=24, pack_size=12)
        elif pattern == 'seasonal':
            item.update(minimum_order=20, pack_size=5)
        # A confirmed incoming order, wholly invented.
        if pattern == 'new':
            item['open_receipts'] = [{'qty': 18, 'date': '2026-11-24'}]
            # The legacy sample schema consumes confirmed monthly receipts;
            # open_receipts alone is descriptive metadata, not engine supply.
            item['receipts'] = {'2026-11': 18}
        items.append(item)
    return dict(dataset='Synthetic construction and hardware catalogue', note=PROVENANCE,
                as_of='2026-10-31', months=MONTHS, items=items)


def emit(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False, allow_nan=False) + '\n', encoding='utf-8')


def sync_fixtures(data):
    emit(ROOT / 'tests/fixtures/original-sample.json', data)
    emit(ROOT / 'tests/fixtures/baselines/643107a/data/sample.json', data)
    compact = json.dumps(data, separators=(',', ':'), ensure_ascii=False)
    paths = [ROOT / 'desktop/plugin.js'] + list((ROOT / 'tests/fixtures/baselines').glob('*/desktop/plugin.js'))
    for path in paths:
        text = path.read_text()
        text, count = re.subn(r'^const SAMPLE = .*$', lambda _: 'const SAMPLE = ' + compact,
                              text, count=1, flags=re.MULTILINE)
        if count != 1:
            raise ValueError(f'Missing sample boundary: {path}')
        path.write_text(text)
    by_sku = {i['sku']: i for i in data['items']}
    replaced = 0
    for path in sorted((ROOT / 'tests/golden').glob('*inputs*.json')):
        value = json.loads(path.read_text())
        def visit(node):
            nonlocal replaced
            if isinstance(node, dict):
                # Golden copies of full sample rows, not independent edge cases.
                if node.get('sku') in by_sku and len(node.get('monthly_sales', [])) == 12:
                    replaced += 1
                    return by_sku[node['sku']].copy()
                return {k: visit(v) for k, v in node.items()}
            return [visit(v) for v in node] if isinstance(node, list) else node
        emit(path, visit(value))
    manifest = ROOT / 'tests/fixtures/baselines/manifest.json'
    digests = json.loads(manifest.read_text())
    for spec in digests:
        revision, relative = spec.split(':', 1)
        digests[spec] = hashlib.sha256((manifest.parent / revision / relative).read_bytes()).hexdigest()
    emit(manifest, digests)
    print(f'Synchronized {len(paths)} embedded sample payloads and {replaced} golden sample inputs')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'data/sample.json')
    parser.add_argument('--sync-fixtures', action='store_true')
    args = parser.parse_args()
    data = generate()
    emit(args.output, data)
    if args.sync_fixtures:
        sync_fixtures(data)
    print(f'{len(data["items"])} products; {PROVENANCE}')


if __name__ == '__main__':
    main()
