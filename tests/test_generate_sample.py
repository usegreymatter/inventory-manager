"""Reproducible fictional catalogue and frozen sample payloads."""
import importlib.util
import json
from pathlib import Path
import random
import re

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('sample_generator', ROOT / 'scripts/generate_sample.py')
assert spec and spec.loader
sample = importlib.util.module_from_spec(spec)
spec.loader.exec_module(sample)


def test_seeded_sample_is_exactly_reproducible_without_global_random_state():
    random.seed(1)
    first = sample.generate()
    random.seed(987)
    assert first == sample.generate()
    assert first == json.loads((ROOT / 'data/sample.json').read_text())
    assert len(first['items']) == 5
    assert first['note'] == 'fully synthetic, generated by scripts/generate_sample.py (seed 731209)'


def test_catalogue_includes_five_deliberate_demand_patterns_and_supply_constraints():
    items = {i['sku']: i for i in sample.generate()['items']}
    smooth, intermittent, seasonal, new, dying = [items[c[0]] for c in sample.CATALOGUE]
    assert all(v > 0 for v in smooth['monthly_sales'])
    assert intermittent['monthly_sales'].count(0) == 8
    assert max(seasonal['monthly_sales']) > 4 * min(seasonal['monthly_sales'])
    assert new['monthly_sales'][:8] == [0] * 8
    assert new['monthly_sales'][-4:] == sorted(new['monthly_sales'][-4:])
    assert dying['monthly_sales'][-4:] == [0] * 4
    assert {i['supplier_days'] for i in items.values()} == {None, 14, 21, 35}
    assert all('Fictional' in i['supplier'] for i in items.values())
    assert smooth['minimum_order'] == 24 and smooth['pack_size'] == 12
    assert seasonal['minimum_order'] == 20 and seasonal['pack_size'] == 5
    assert new['open_receipts'] == [{'qty': 18, 'date': '2026-11-24'}]
    assert new['receipts'] == {'2026-11': 18}  # engine-consumed confirmed supply


def test_all_frozen_sample_payloads_match_the_seeded_generator():
    expected = sample.generate()
    for relative in ('tests/fixtures/original-sample.json',
                     'tests/fixtures/baselines/643107a/data/sample.json'):
        assert json.loads((ROOT / relative).read_text()) == expected
    paths = [ROOT / 'desktop/plugin.js', *(ROOT / 'tests/fixtures/baselines').glob('*/desktop/plugin.js')]
    assert len(paths) == 11
    for path in paths:
        match = re.search(r'^const SAMPLE = (.*)$', path.read_text(), re.MULTILINE)
        assert match, str(path)
        assert json.loads(match.group(1)) == expected, str(path)


def test_every_sample_golden_input_uses_generated_values_not_retired_quantities():
    expected = {i['sku']: i for i in sample.generate()['items']}
    inputs = json.loads((ROOT / 'tests/golden/inputs.json').read_text())
    copied = {c['item']['sku']: c['item'] for c in inputs['cases'] if c['item']['sku'] in expected}
    assert copied == expected
